func TestStrmFingerprint(t *testing.T) {
	refA := &StrmReference{Raw: "http://nas/d/miaa-131.mkv"}
	refB := &StrmReference{Raw: "HTTP://NAS/d/miaa-131.mkv"}

	same1 := StrmFingerprint(1, "a/miaa-131.(mkv).strm", refA)
	same2 := StrmFingerprint(1, "b/other-name.strm", refB)
	if same1 != same2 {
		t.Errorf("same target in the same directory should share a fingerprint: %q vs %q", same1, same2)
	}

	// 同一目标地址在不同目录中也视为同一视频（与物理文件按内容去重的语义一致）。
	if StrmFingerprint(2, "a/miaa-131.(mkv).strm", refA) != same1 {
		t.Errorf("identical targets should share a fingerprint across directories")
	}

	// 关键：扩展名变化（如重新指向不同清晰度）必须产生新指纹，以触发重新刮削。
	otherExt := StrmFingerprint(1, "a/miaa-131.(mkv).strm", &StrmReference{Raw: "http://nas/d/miaa-131.mp4"})
	if otherExt == same1 {
		t.Errorf("different targets must not share a fingerprint")
	}

	fallback1 := StrmFingerprint(1, "a/empty.strm", nil)
	fallback2 := StrmFingerprint(1, "b/empty.strm", nil)
	if fallback1 == fallback2 {
		t.Errorf("empty strm entries should fall back to path-based fingerprints")
	}
	if fallback1 == same1 {
		t.Errorf("fallback fingerprint must not collide with a resolved target")
	}
}

func TestStrmPlaybackTargetFromReference(t *testing.T) {
	tests := []struct {
		name      string
		ref       *StrmReference
		wantURL   bool
		wantLocal bool
		wantExt   string
	}{
		{
			name:    "url target",
			ref:     &StrmReference{Kind: StrmTargetURL, URL: "http://nas/a.mkv", Extension: ".mkv"},
			wantURL: true,
			wantExt: ".mkv",
		},
		{
			name:      "local target",
			ref:       &StrmReference{Kind: StrmTargetPath, Path: `/mnt/v/a.mp4`, Extension: ".mp4"},
			wantLocal: true,
			wantExt:   ".mp4",
		},
		{
			name: "empty target rejected",
			ref:  &StrmReference{Kind: StrmTargetURL, URL: "   "},
		},
		{
			name: "nil reference rejected",
		},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			got, ok := StrmPlaybackTargetFromReference(tt.ref)
			if tt.wantURL || tt.wantLocal {
				if !ok {
					t.Fatalf("expected a usable target")
				}
			} else if ok {
				t.Fatalf("expected the target to be rejected, got %+v", got)
			}
			if got.IsURL() != tt.wantURL || got.IsLocal() != tt.wantLocal {
				t.Errorf("url=%v local=%v, want url=%v local=%v", got.IsURL(), got.IsLocal(), tt.wantURL, tt.wantLocal)
			}
			if tt.wantExt != "" && got.Extension != tt.wantExt {
				t.Errorf("extension = %q, want %q", got.Extension, tt.wantExt)
			}
		})
	}
}

func TestParseStrmReferenceUTF16LE(t *testing.T) {
	content := "http://host/a.mkv"
	raw := []byte{0xFF, 0xFE}
	for _, r := range content {
		raw = append(raw, byte(r), 0)
	}
	ref, err := ParseStrmReferenceBytes(raw)
	if err != nil {
		t.Fatalf("ParseStrmReferenceBytes() error = %v", err)
	}
	if ref.Raw != content {
		t.Fatalf("raw = %q, want %q", ref.Raw, content)
	}
	if ref.Kind != StrmTargetURL {
		t.Fatalf("kind = %v, want StrmTargetURL", ref.Kind)
	}
}
